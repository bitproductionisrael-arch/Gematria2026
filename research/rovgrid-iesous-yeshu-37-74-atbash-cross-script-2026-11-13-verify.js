const A = word => [...word.toUpperCase()].reduce((s,c)=>s+27-rows[c],0);
const small = word => [...word.toUpperCase()].reduce((s,c)=>s+(1+(rows[c]-1)%9),0);
const J = {Y:400,E:5,S:90,H:8,U:200,I:9,O:50};
const jewish = word => [...word.toUpperCase()].reduce((s,c)=>s+J[c],0);
const eq=(a,b,label)=>{assert.equal(a,b,label);console.log('PASS '+label+': '+b);};
eq(S('IESOUS'),88,'IESOUS Simple');
eq(A('IESOUS'),74,'IESOUS Atbash');
